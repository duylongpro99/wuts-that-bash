#!/bin/sh
# Print the Homebrew formula for a release, from its .sha256 files.
# Usage: scripts/homebrew-formula.sh 0.2.0 dist/   (dist/ holds wib-<target>.tar.gz.sha256)
set -eu
version=$1
dir=$2
base="https://github.com/duylongpro99/wuts-that-bash/releases/download/v$version"

sha() {
  file="$dir/wib-$1.tar.gz.sha256"
  [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
  sum=$(cut -d' ' -f1 "$file")
  case $sum in
    *[!0-9a-f]* | "") echo "bad checksum in $file" >&2; exit 1 ;;
  esac
  [ ${#sum} -eq 64 ] || { echo "bad checksum in $file" >&2; exit 1; }
  printf '%s' "$sum"
}

# Computed first: a failure inside the heredoc would not stop the script.
mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_intel=$(sha x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew-formula.sh in duylongpro99/wuts-that-bash; edits are overwritten on release.
class Wib < Formula
  desc "Shell history suggestions under your zsh prompt as you type"
  homepage "https://github.com/duylongpro99/wuts-that-bash"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/wib-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/wib-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/wib-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/wib-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "wib"
  end

  def caveats
    <<~TEXT
      Add this to the end of ~/.zshrc (after oh-my-zsh and other plugins), then open a new terminal:
        eval "\$(wib init zsh)"
      After an upgrade, open a new terminal so zsh loads the new version.
    TEXT
  end

  test do
    assert_match "wib #{version}", shell_output("#{bin}/wib --version")
  end
end
EOF
